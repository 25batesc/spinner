// Renders a stack spec plus one session into a compose file (docs/STACK_SPEC.md, "Services").
// This module is pure: it takes the spec and the facts the runner gathered (worktree paths,
// lockfile hashes) and returns text. The snapshot test in `compose.test.ts` pins the output
// for `examples/sample-stack`, so a change here is reviewed as a diff of the compose file.
import assert from "node:assert/strict";
import { posix } from "node:path";
import { stringify } from "yaml";
import type { DepsVolume, ServiceRuntime, StackService, StackSpec } from "@spinner/protocol";

/** Where a service's worktree is bind-mounted inside its container. */
export const APP_DIR = "/app";

export interface RenderSession {
    /** Short id, for example `s17`. */
    id: string;
    branch: string;
    /** Absolute path of the session directory. */
    dir: string;
    /** Name of the session's database. */
    db: string;
}

export interface DepsInfo {
    /** Hash of the lockfile, which keys the shared volume. */
    hash: string;
    /** File name of the lockfile, which picks the install command. */
    lockfile: string;
    /**
     * Directory of the lockfile relative to the worktree root, `.` at the root. In a pnpm or
     * npm workspace that is the root even when `workdir` is a package below it, and the
     * dependency volume mounts there.
     */
    dir: string;
}

export interface RenderInput {
    spec: StackSpec;
    session: RenderSession;
    /** Absolute worktree path per repo. */
    worktrees: Record<string, string>;
    /** Lockfile facts per service that has a `deps_volume`. */
    deps: Record<string, DepsInfo>;
}

export interface EnvFile {
    /** Absolute path inside the worktree. */
    path: string;
    content: string;
}

export interface Rendered {
    /** The compose file text. */
    compose: string;
    /** The `.env` text next to it, so a hand-run `docker compose` sees the same variables. */
    env: string;
    /** Service name to hostname, for `session.yaml` and the printed URLs. */
    hosts: Record<string, string>;
    /** Names of the shared dependency volumes the runner must create before `up`. */
    deps_volumes: string[];
    /** Files to write into worktrees before `up`, for `env_file` services. */
    env_files: EnvFile[];
}

export function compose_project(session_id: string): string {
    return `spinner-${session_id}`;
}

/**
 * The session network. It is external to compose: the runner creates it before `up` and
 * attaches the proxy and the shared Postgres to it, so services find `postgres` by name
 * from their first second, and removes it at `close`.
 */
export function compose_network(session_id: string): string {
    return compose_project(session_id);
}

export function hostname(host: string, session_id: string): string {
    return `${host}.${session_id}.localhost`;
}

export function render_compose(input: RenderInput): Rendered {
    const { spec, session } = input;
    assert.ok(/^s\d+$/.test(session.id), `session id must look like s17: ${session.id}`);
    const services: Record<string, unknown> = {};
    const volumes: Record<string, unknown> = {};
    const hosts: Record<string, string> = {};
    const env_files: EnvFile[] = [];
    const deps_volumes: string[] = [];
    for (const [name, service] of Object.entries(spec.services)) {
        const rendered = render_service(name, service, input);
        services[name] = rendered.service;
        for (const volume of rendered.named_volumes) {
            volumes[volume] = {};
        }
        if (rendered.deps_volume !== null) {
            volumes[rendered.deps_volume] = { name: rendered.deps_volume, external: true };
            deps_volumes.push(rendered.deps_volume);
        }
        if (service.host !== undefined) {
            hosts[name] = hostname(service.host, session.id);
        }
        if (rendered.env_file !== null) {
            env_files.push(rendered.env_file);
        }
    }
    const document: Record<string, unknown> = {
        name: compose_project(session.id),
        services,
        networks: { default: { name: compose_network(session.id), external: true } },
    };
    if (Object.keys(volumes).length > 0) {
        document["volumes"] = volumes;
    }
    const env = [
        `COMPOSE_PROJECT_NAME=${compose_project(session.id)}`,
        `SESSION_ID=${session.id}`,
        `SESSION_DB=${session.db}`,
        `SESSION_BRANCH=${session.branch}`,
        `SESSION_DIR=${session.dir}`,
        "",
    ].join("\n");
    const header = "# Generated by spinner from spinner.yaml. Do not edit; edit the spec.\n";
    return {
        compose: header + stringify(document, { lineWidth: 0 }),
        env,
        hosts,
        deps_volumes,
        env_files,
    };
}

interface RenderedService {
    service: Record<string, unknown>;
    /** Session-scoped named volumes from the spec's `volumes` list. */
    named_volumes: string[];
    /** The shared dependency volume, or null. */
    deps_volume: string | null;
    env_file: EnvFile | null;
}

function render_service(
    name: string,
    service: StackService,
    input: RenderInput,
): RenderedService {
    const { spec, session } = input;
    const workdir = service_workdir(service);
    const env = substitute_env(service.env ?? {}, session, spec.pass_env ?? []);
    const out: Record<string, unknown> = { image: service.image };
    const mounts: string[] = [];
    const named_volumes: string[] = [];
    let deps_volume: string | null = null;
    let env_file: EnvFile | null = null;
    if (service.repo !== undefined) {
        const worktree = input.worktrees[service.repo];
        assert.ok(worktree !== undefined, `no worktree for repo ${service.repo}`);
        mounts.push(`${worktree}:${APP_DIR}`);
        out["working_dir"] = workdir;
        if (service.env_file !== undefined) {
            const path = posix.join(worktree, service.env_file);
            env_file = { path, content: render_dotenv(env) };
        }
    }
    const deps = render_deps(name, service, input);
    if (deps !== null) {
        deps_volume = deps.volume;
        mounts.push(`${deps.volume}:${deps.mount}`);
    }
    for (const volume of service.volumes ?? []) {
        mounts.push(volume);
        const source = volume.split(":")[0] ?? "";
        if (is_named_volume(source)) {
            named_volumes.push(source);
        }
    }
    if (service.command !== undefined) {
        out["command"] = render_command(service, deps);
    }
    if (Object.keys(env).length > 0) {
        out["environment"] = env;
    }
    if (mounts.length > 0) {
        out["volumes"] = mounts;
    }
    if (service.healthcheck !== undefined) {
        assert.ok(service.port !== undefined, `services.${name}: healthcheck needs a port`);
        out["healthcheck"] = render_healthcheck(service.healthcheck, service.port, service.runtime);
    }
    const depends_on = service.depends_on ?? [];
    if (depends_on.length > 0) {
        out["depends_on"] = Object.fromEntries(
            depends_on.map((other) => [other, { condition: depends_condition(spec, other) }]),
        );
    }
    if (service.host !== undefined) {
        assert.ok(service.port !== undefined, `services.${name}: host needs a port`);
        out["labels"] = render_labels(name, service.host, service.port, spec, session);
    }
    return { service: out, named_volumes, deps_volume, env_file };
}

function service_workdir(service: StackService): string {
    const workdir = service.workdir ?? ".";
    assert.ok(!posix.isAbsolute(workdir), `workdir must be relative to the worktree: ${workdir}`);
    return posix.normalize(posix.join(APP_DIR, workdir));
}

/** The variables a spec may use in `env`, from docs/STACK_SPEC.md. */
function session_variables(session: RenderSession): Record<string, string> {
    return {
        SESSION_ID: session.id,
        SESSION_DB: session.db,
        SESSION_BRANCH: session.branch,
        SESSION_DIR: session.dir,
    };
}

/**
 * Replaces the session variables. Other `${NAME}` references stay as they are: compose reads
 * them from the host environment at `up`, which is how `pass_env` keys reach a container
 * without Spinner writing their values to disk.
 */
function substitute_env(
    env: Record<string, string>,
    session: RenderSession,
    pass_env: string[],
): Record<string, string> {
    const variables = session_variables(session);
    const out: Record<string, string> = {};
    for (const [key, value] of Object.entries(env)) {
        out[key] = substitute(String(value), variables);
    }
    for (const key of pass_env) {
        assert.ok(/^[A-Z_][A-Z0-9_]*$/.test(key), `pass_env entry is not a variable name: ${key}`);
        out[key] = `\${${key}}`;
    }
    return out;
}

function substitute(text: string, variables: Record<string, string>): string {
    return text.replace(/\$\{([A-Z_][A-Z0-9_]*)\}/g, (whole, name: string) => {
        const value = variables[name];
        return value === undefined ? whole : value;
    });
}

function render_dotenv(env: Record<string, string>): string {
    const lines = Object.entries(env).map(([key, value]) => `${key}=${value}`);
    const header = "# Written by spinner before each start. Edit spinner.yaml, not this file.";
    return `${header}\n${lines.join("\n")}\n`;
}

interface DepsRender {
    volume: string;
    /** Absolute container path the volume covers, for example `/app/node_modules`. */
    mount: string;
    /** Shell command that installs into that directory, run from the lockfile's directory. */
    install: string;
}

/** Install commands per dependency-volume kind. The lockfile name picks the Python tool. */
const DEPS_DIR: Record<DepsVolume, string> = {
    "pnpm-store": "node_modules",
    "npm-cache": "node_modules",
    "yarn-cache": "node_modules",
    venv: ".venv",
};

function deps_install(kind: DepsVolume, lockfile: string): string {
    if (kind === "pnpm-store") {
        return "pnpm install --frozen-lockfile";
    }
    if (kind === "npm-cache") {
        return "npm ci";
    }
    if (kind === "yarn-cache") {
        return "yarn install --frozen-lockfile";
    }
    if (lockfile === "uv.lock") {
        return "uv sync --frozen";
    }
    if (lockfile === "poetry.lock") {
        return "poetry install";
    }
    return `python -m venv .venv && .venv/bin/pip install -r ${lockfile}`;
}

function render_deps(name: string, service: StackService, input: RenderInput): DepsRender | null {
    if (service.deps_volume === undefined) {
        return null;
    }
    const info = input.deps[name];
    assert.ok(info !== undefined, `services.${name} has deps_volume but no lockfile hash`);
    assert.ok(/^[0-9a-f]{12,}$/.test(info.hash), `lockfile hash must be hex: ${info.hash}`);
    const lock_dir = posix.normalize(posix.join(APP_DIR, info.dir));
    return {
        volume: `spinner-deps-${service.deps_volume}-${info.hash.slice(0, 12)}`,
        mount: posix.join(lock_dir, DEPS_DIR[service.deps_volume]),
        install: `cd ${lock_dir} && ${deps_install(service.deps_volume, info.lockfile)}`,
    };
}

/**
 * The container command: the wrapper and the command, behind an install guard when the
 * service has a dependency volume. The guard needs a shell, so only then is the command
 * wrapped in `sh -c`; a plain string keeps the image's own entrypoint (Temporal's `temporal`)
 * in front. A marker file in the volume says the install finished, so a volume shared by
 * many sessions installs once.
 */
function render_command(service: StackService, deps: DepsRender | null): string | string[] {
    assert.ok(service.command !== undefined);
    const wrapper = service.wrapper === undefined ? "" : `${wrapper_path(service.wrapper)} `;
    const command = `${wrapper}${service.command.trim()}`;
    if (deps === null) {
        return command;
    }
    const marker = `${deps.mount}/.spinner-ready`;
    const guard = `if [ ! -f ${marker} ]; then (${deps.install}) && touch ${marker}; fi`;
    return ["sh", "-c", `${guard} && exec ${command}`];
}

/** A wrapper is a path relative to the worktree, so it must resolve from any `workdir`. */
function wrapper_path(wrapper: string): string {
    const [first, ...rest] = wrapper.trim().split(/\s+/);
    assert.ok(first !== undefined && first.length > 0, "wrapper must not be empty");
    const on_path = posix.isAbsolute(first) || !first.includes("/");
    const absolute = on_path ? first : posix.join(APP_DIR, first);
    return [absolute, ...rest].join(" ");
}

function is_named_volume(source: string): boolean {
    return !(source.startsWith("/") || source.startsWith(".") || source.startsWith("~"));
}

/** Health probes use the runtime's own interpreter, because slim images have no curl or wget. */
function render_healthcheck(check: string, port: number, runtime?: ServiceRuntime): unknown {
    const match = /^GET\s+(\/\S*)$/.exec(check.trim());
    assert.ok(match?.[1] !== undefined, `healthcheck must be "GET /path": ${check}`);
    const url = `http://127.0.0.1:${port}${match[1]}`;
    const python = "import urllib.request,sys;" +
        `sys.exit(0 if urllib.request.urlopen('${url}').status<300 else 1)`;
    const node = `fetch('${url}').then(r=>process.exit(r.ok?0:1),()=>process.exit(1))`;
    const probe = runtime === "python" ? ["python", "-c", python] : ["node", "-e", node];
    // Docker probes every `start_interval` during `start_period` (its default is 5 s, which
    // alone costs 5 s per dependency level), then every `interval`. A success at any time
    // marks the service healthy; failures during the start period do not count.
    return {
        test: ["CMD", ...probe],
        interval: "2s",
        timeout: "3s",
        retries: 30,
        start_period: "60s",
        start_interval: "250ms",
    };
}

function depends_condition(spec: StackSpec, other: string): string {
    const target = spec.services[other];
    assert.ok(target !== undefined, `depends_on ${other} is not a service`);
    return target.healthcheck === undefined ? "service_started" : "service_healthy";
}

/**
 * Traefik routes by these labels. Router and service names carry the session id so two
 * sessions never share one. `traefik.docker.network` tells Traefik which network to reach
 * the container on; the runner connects the proxy to that network after `up`.
 */
function render_labels(
    name: string,
    host: string,
    port: number,
    spec: StackSpec,
    session: RenderSession,
): Record<string, string> {
    const router = `${compose_project(session.id)}-${name}`;
    const labels: Record<string, string> = {
        "traefik.enable": "true",
        "traefik.docker.network": compose_network(session.id),
        [`traefik.http.routers.${router}.rule`]: `Host(\`${hostname(host, session.id)}\`)`,
        [`traefik.http.routers.${router}.entrypoints`]: "web",
        [`traefik.http.services.${router}.loadbalancer.server.port`]: String(port),
    };
    const strip = spec.proxy?.strip_frame_headers ?? [];
    if (strip.includes(name)) {
        // An empty value makes Traefik delete the header. CSP cannot be edited per directive,
        // so the whole policy goes; that is acceptable for a dev tool embedded in a pane.
        const prefix = `traefik.http.middlewares.${router}-frames.headers.customresponseheaders`;
        labels[`${prefix}.X-Frame-Options`] = "";
        labels[`${prefix}.Content-Security-Policy`] = "";
        labels[`traefik.http.routers.${router}.middlewares`] = `${router}-frames`;
    }
    return labels;
}
